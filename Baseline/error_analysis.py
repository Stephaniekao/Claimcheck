"""Field 9 error analysis from the saved test predictions (does NOT rerun the baseline).

    python3 Baseline/error_analysis.py

For each RAGBench subset it samples (seed 42):
  * 30 missed errors  - gold Unsupported, labeled Supported
  * 20 false alarms   - gold Supported, labeled Unsupported
and lists every Inserted Error Set / Storyboard B error (the baseline has none).

`suggested_category` is a keyword heuristic to speed up review. It is NOT the
final category: the card asks a team member to assign `reviewer_1_category`
and a second member to check 10 per method in `reviewer_2_category`.
"""
from __future__ import annotations

import json

import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from claimcheck_baseline import keywords as kw  # noqa: E402
from claimcheck_baseline.normalize import extract_periods, years_of  # noqa: E402
from claimcheck_baseline.rules import is_derived  # noqa: E402

BASE = Path(__file__).resolve().parent
OUT = BASE / "outputs"
EA = OUT / "error_analysis"
RAG = BASE.parent / "Data" / "RAGBench"
SEED = 42
CATEGORIES = ["scope", "wrong period or year", "number or unit format", "calculated values",
              "different wording", "citation problem", "other"]


# Conclusions drawn from earlier steps ("Therefore, 9.77% of ...", "1 out of 181").
_CONCLUSION = re.compile(r"\b(?:therefore|thus|hence|so,|this means|out of|in total)\b|%\s+of\b", re.I)


def suggest(row: pd.Series) -> str:
    claim, rule = row.claim, row.rule
    if rule == "no_passage":
        return "citation problem"
    if kw.scope_of(claim) == "segment" or kw.find_segments(claim) or (
            kw.scope_of(claim) == "total" and "segment" in str(row.get("passage", "")).lower()):
        return "scope"
    if is_derived(claim) or _CONCLUSION.search(claim) or (
            rule in ("amount_not_in_passage", "same_item_different_amount") and "%" in claim):
        return "calculated values"
    if len(years_of(extract_periods(claim))) >= 2:
        return "wrong period or year"
    if rule == "amount_not_in_passage":
        return "number or unit format"
    if rule in ("same_item_different_amount", "amount_matches_other_item"):
        return "different wording"
    return "other"


def passages(subset: str, ids: set[int]) -> dict[int, str]:
    df = pd.read_parquet(RAG / subset / "test.parquet", columns=["documents_sentences"])
    return {i: "\n".join(s[1] for doc in df.documents_sentences.iloc[i] for s in doc) for i in ids}


def sample(df: pd.DataFrame, n: int) -> pd.DataFrame:
    return df.sample(min(n, len(df)), random_state=SEED).sort_index()


def main() -> None:
    EA.mkdir(parents=True, exist_ok=True)
    ins_m = json.loads((OUT / "inserted_metrics.json").read_text())
    rag_m = json.loads((OUT / "ragbench_metrics_test.json").read_text())
    ins_rules = ins_m.get("test_from", ins_m).get("versions", {}).get("rules")
    ins_data = ins_m.get("test_from", ins_m).get("provenance", {}).get("inserted_error_set", {}).get("version", "v1")
    rag_rules = rag_m["versions"]["rules"]
    lines = ["# Baseline error analysis (test splits)", "",
             f"Inserted Error Set {ins_data}: rules {ins_rules}. RAGBench: rules {rag_rules} "
             "(its test split was used once, with that version).", "",
             "Generated by `Baseline/error_analysis.py` from the saved test predictions. "
             "`suggested_category` is a keyword heuristic; final categories are assigned by reviewers in the CSVs.", ""]

    # Inserted Error Set: every error, and every Storyboard B error.
    ins = pd.read_csv(OUT / "inserted_predictions_test.csv")
    wrong = ins[(ins.label == "Unsupported") & (ins.pred != "Unsupported") |
                (ins.label == "Supported") & (ins.pred != "Supported")]
    wrong.to_csv(EA / "inserted_test_errors.csv", index=False)
    sb = ins[ins.subset == "storyboard_b"]
    sb_wrong = wrong[wrong.subset == "storyboard_b"]
    lines += [f"## Inserted Error Set {ins_data} ({len(ins)} test claims)", "",
              f"- Errors: **{len(wrong)}** of {len(ins)} (Storyboard B: {len(sb_wrong)} of {len(sb)})."]
    if sb_wrong.empty:
        lines.append("- Storyboard B scope errors were all caught by `same_item_different_amount`: the passage states the "
                     "total revenue, so the claim's segment figure contradicts it. None were labeled Uncertain.")
    per_type = ins.groupby("error_type").apply(lambda g: f"{(g.pred == g.label).sum()}/{len(g)}", include_groups=False)
    lines += ["- Correct by error type: " + ", ".join(f"{k} {v}" for k, v in per_type.items()), ""]

    # Reference: label everything Unsupported.
    lines += ["## Reference: label every claim Unsupported", "", "| Subset | Level | Base rate (= precision) | F1 |", "|---|---|---|---|"]
    for name, df in [("Inserted Error Set", ins.assign(answer=range(len(ins)), answer_label=ins.label))]:
        b = (df.label == "Unsupported").mean()
        lines.append(f"| {name} | claim | {b:.3f} | {2 * b / (1 + b):.3f} |")

    summary_rows = []
    for subset in ["FinQA", "TATQA"]:
        claims = pd.read_csv(OUT / f"ragbench_{subset.lower()}_test_claims.csv")
        answers = claims.groupby("answer").answer_label.first()
        for level, gold in [("claim", claims.label), ("answer", answers)]:
            b = (gold == "Unsupported").mean()
            lines.append(f"| RAGBench {subset} | {level} | {b:.3f} | {2 * b / (1 + b):.3f} |")

        missed = claims[(claims.label == "Unsupported") & (claims.pred == "Supported")]
        false_alarm = claims[(claims.label == "Supported") & (claims.pred == "Unsupported")]
        picks = {"missed_30": sample(missed, 30), "false_alarms_20": sample(false_alarm, 20)}
        text = passages(subset, set(pd.concat(picks.values()).answer))
        for tag, df in picks.items():
            df = df.copy()
            df["passage"] = df.answer.map(text)
            df["suggested_category"] = df.apply(suggest, axis=1)
            df["reviewer_1_category"] = ""
            df["reviewer_2_category"] = ""
            cols = ["answer", "id", "key", "claim", "label", "pred", "rule", "explanation", "suggested_category",
                    "reviewer_1_category", "reviewer_2_category", "passage"]
            df[cols].to_csv(EA / f"ragbench_{subset.lower()}_{tag}.csv", index=False)
            counts = df.suggested_category.value_counts()
            summary_rows.append({"subset": subset, "set": tag, "pool": len(missed if tag.startswith("missed") else false_alarm),
                                 "sampled": len(df), **{c: int(counts.get(c, 0)) for c in CATEGORIES}})

    lines += ["", "## RAGBench samples (suggested categories)", "",
              "*Missed* = wrong claim labeled Supported. *False alarm* = correct claim labeled Unsupported. "
              "Pool = all such claims on test.", ""]
    tab = pd.DataFrame(summary_rows)
    lines.append("| Subset | Set | Pool | Sampled | " + " | ".join(CATEGORIES) + " |")
    lines.append("|" + "---|" * (4 + len(CATEGORIES)))
    for r in tab.itertuples(index=False):
        lines.append("| " + " | ".join(str(x) for x in r) + " |")
    lines += ["", "**Confidence on misses (Field 9):** the baseline gives no score, but every missed error was labeled "
              "Supported by its strongest rule (`amount_and_keywords_match`: the number *and* the key words matched). "
              "These are the card's worst case, a wrong claim that looks fully supported. In the samples the numbers "
              "really are in the passage (many are list fragments such as \"- Commercial mortgages at fair value: "
              "$772 million\"); what is wrong is what the sentence asserts with them, or RAGBench's GPT-4 annotator "
              "may disagree with the passage. Number matching cannot see either, so these need a human look.", "",
              "**False alarms:** mostly calculated values the answer derived (percent of total, sums such as "
              "\"1 out of the 181 leased locations\" where the passage only says 81 outside the US) and "
              "different wording between the claim and the table row label.", ""]
    (EA / "summary.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
