"""Keyword extraction: line items, scope (total vs segment) and segment names.

The lexicon was written from the Inserted Error Set *training* split and from
the XBRL standard labels; it was not edited after looking at validation/test.
"""
from __future__ import annotations

import re

KEYWORDS_VERSION = "1.0.0"

# canonical item -> regex patterns. Order matters: more specific items first,
# and their matched spans are masked so "current assets" is not also "assets".
LINE_ITEMS: list[tuple[str, list[str]]] = [
    ("operating_cash_flow", [r"net cash (?:provided by |from |generated (?:by|from) )?(?:\(used in\) |used in |\(used for\) )?operating activities",
                             r"cash (?:flows? )?from operations", r"operating cash flows?",
                             r"cash (?:provided by|generated by|from) operating activities"]),
    ("investing_cash_flow", [r"net cash (?:provided by |from )?(?:\(used in\) |used in |\(used for\) )?investing activities",
                             r"cash (?:flows? )?(?:used in|from|provided by) investing activities", r"investing cash flows?"]),
    ("financing_cash_flow", [r"net cash (?:provided by |from )?(?:\(used in\) |used in |\(used for\) )?financing activities",
                             r"cash (?:flows? )?(?:used in|from|provided by) financing activities", r"financing cash flows?"]),
    ("cash", [r"cash and cash equivalents", r"cash and equivalents", r"cash & cash equivalents"]),
    ("current_assets", [r"(?:total )?current assets", r"assets,? current"]),
    ("current_liabilities", [r"(?:total )?current liabilities", r"liabilities,? current"]),
    ("equity", [r"(?:total )?(?:stockholders|shareholders|share ?owners)['’]? equity", r"total equity"]),
    ("cost_of_revenue", [r"cost of (?:total )?revenues?", r"cost of (?:goods (?:and services )?|products )?sold",
                         r"cost of sales"]),
    ("gross_profit", [r"gross (?:profit|margin)"]),
    ("operating_income", [r"operating income(?: \(loss\))?", r"income from operations", r"operating (?:profit|earnings)",
                          r"operating loss"]),
    ("net_income", [r"net (?:income|earnings|loss)(?: \(loss\))?(?: attributable to [a-z ]+)?", r"net profit"]),
    ("assets", [r"total assets", r"\bassets\b"]),
    ("liabilities", [r"total liabilities", r"\bliabilities\b"]),
    ("revenue", [r"revenues? from contracts? with customers?(?:,? (?:excluding|including) assessed tax)?",
                 r"(?:total |net |operating )?revenues?", r"net sales", r"total sales", r"\bsales\b", r"turnover"]),
    ("eps", [r"(?:diluted |basic )?earnings per (?:common )?share", r"\beps\b"]),
]
_COMPILED = [(item, [re.compile(p, re.I) for p in pats]) for item, pats in LINE_ITEMS]

TOTAL_WORDS = re.compile(r"\b(?:total|entire|whole|overall|consolidated|company[- ]wide|all of (?:the )?company)\b", re.I)
SEGMENT_WORDS = re.compile(r"\b(?:segments?|divisions?|business units?|reportable|operating segment)\b", re.I)
# XBRL members ("MealsBeveragesMember") and "<Name> segment" phrases.
_MEMBER_RE = re.compile(r"\b([A-Z][A-Za-z0-9]+Member)\b")
_NAMED_SEGMENT_RE = re.compile(r"\b((?:[A-Z][\w&]*\s){1,4})(?:segment|division)\b")

STOPWORDS = set("""a an the of for in on at to by from and or with was were is are be been as its it's it this that these
those which who than then into over under per company company's companies fiscal year years period periods ended ending
end usd us$ million millions billion billions thousand thousands total amount reported report reports approximately about
around compared versus vs also had has have did do does respectively during while their they our we""".split())


def find_items(text: str) -> set[str]:
    """Canonical line items mentioned in the text."""
    lowered = text.lower().replace("’", "'")
    found: set[str] = set()
    for item, pats in _COMPILED:
        for p in pats:
            hit = False
            for m in p.finditer(lowered):
                hit = True
                lowered = lowered[: m.start()] + " " * (m.end() - m.start()) + lowered[m.end():]
            if hit:
                found.add(item)
    return found


def find_segments(text: str) -> set[str]:
    names = {m.group(1).lower() for m in _MEMBER_RE.finditer(text)}
    for m in _NAMED_SEGMENT_RE.finditer(text):
        name = m.group(1).strip().lower()
        if name not in {"the", "each", "our", "this", "a", "one", "other", "total", "reportable"}:
            names.add(name)
    return names


def scope_of(text: str) -> str | None:
    """'segment', 'total' or None.

    'Total' wins when both appear in a claim, because a claim such as
    "X's Meals segment revenue represented the company's entire revenue"
    is asserting something about the total.
    """
    has_total = bool(re.search(r"\b(?:entire|whole|overall|consolidated|company[- ]wide)\b", text, re.I))
    has_segment = bool(SEGMENT_WORDS.search(text)) or bool(_MEMBER_RE.search(text))
    if has_total:
        return "total"
    if has_segment:
        return "segment"
    if TOTAL_WORDS.search(text):
        return "total"
    return None


def content_words(text: str) -> set[str]:
    words = re.findall(r"[a-z][a-z&'-]+", text.lower())
    return {w.strip("'") for w in words if w not in STOPWORDS and len(w) > 2}
